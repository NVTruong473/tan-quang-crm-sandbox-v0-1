import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const functionDir = dirname(fileURLToPath(import.meta.url));
const projectDir = resolve(functionDir, "../../..");
const dataDir = resolve(projectDir, "dist/data");
const names = ["customer_360.csv", "scoring_sandbox.csv", "opportunities.csv", "crm_activities.csv"];
const files = {};

for (const name of names) files[`data/${name}`] = await readFile(resolve(dataDir, name), "utf8");

await writeFile(
  resolve(functionDir, "data.ts"),
  `// Generated by build-data.mjs. Do not edit directly.\nexport const DATA_FILES = ${JSON.stringify(files, null, 2)} as const;\n`,
  "utf8",
);
